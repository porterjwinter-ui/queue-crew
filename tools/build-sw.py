#!/usr/bin/env python3
"""Writes sw.js with every app file listed and a version hash, so phones get updates
and the whole app works offline after the first visit. Run after changing any file."""
import hashlib, json, os, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
files = ['./']
h = hashlib.sha1()
for base in ['index.html', 'manifest.webmanifest', 'css', 'js', 'data', 'icons']:
    p = root / base
    paths = [p] if p.is_file() else sorted(x for x in p.rglob('*') if x.is_file())
    for f in paths:
        rel = './' + f.relative_to(root).as_posix()
        files.append(rel)
        h.update(rel.encode()); h.update(f.read_bytes())
version = h.hexdigest()[:10]

sw = f"""// Generated by tools/build-sw.py — offline cache for Queue Crew.
const VERSION = 'qc-{version}';
const ASSETS = {json.dumps(files, indent=2)};

self.addEventListener('install', (e) => {{
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
}});

self.addEventListener('activate', (e) => {{
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== VERSION).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
}});

// Cache first (lines have bad signal), falling back to the network.
self.addEventListener('fetch', (e) => {{
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(
    caches.match(e.request, {{ ignoreSearch: true }}).then((hit) => hit || fetch(e.request).then((res) => {{
      const copy = res.clone();
      caches.open(VERSION).then((c) => c.put(e.request, copy));
      return res;
    }}).catch(() => caches.match('./index.html')))
  );
}});
"""
(root / 'sw.js').write_text(sw)
print(f'sw.js: {len(files)} files, version {version}')
